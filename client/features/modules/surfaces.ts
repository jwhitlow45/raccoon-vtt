import type { ModuleId } from "./registry.ts";

/**
 * Every client file that holds a control site, each placed once
 * (docs/design/design-v1-features.md 14, checks 5 and 6). A drawn surface is
 * a row of the design's surface table, which parts.markup.test.ts draws. A
 * probe names the e2e check that covers it, a runtime gate its test, and a
 * core file its reason. `sites` is the file's control-site count from
 * controlSites.ts, so a control added anywhere, in any branch, fails
 * surfaces.scan.test.ts until its entry is placed again (D-261127-420).
 *
 * The first list was written from the scan in one go and then read file by
 * file (D-261127-425). It is plain data from then on: when the scan fails,
 * place the entry by hand.
 */

/** Where a file's controls are checked. `covers` names the parts its drawing, probe or test must show. */
export type Placement =
  | { kind: "drawn"; surface: string; covers: readonly ModuleId[] }
  | { kind: "probe"; probe: string; covers: readonly ModuleId[] }
  | { kind: "runtime"; test: string; covers: readonly ModuleId[] }
  | { kind: "core"; reason: string };

export type SurfaceEntry = { file: string; sites: number } & Placement;

