import { ABILITY_KEYS, SKILL_KEYS, type AbilityKey, type Actor, type Character, type CompanionBlock, type ConditionKey, type CustomMonster, type RollRequest, type SkillKey, type SrdId, type StatBlock, type Token } from "../model.ts";
import type { ActorTarget } from "../protocol.ts";
import type { DamageType } from "../rules/damage.ts";
import { pcDerived } from "../rules/pcStats.ts";
import { SKILLS } from "../rules/skills.ts";
import { abilityMod } from "../statBlock.ts";

/**
 * A creature's numbers and the d20 rolls they feed (docs/design-v1-dice.md
 * 6): one function on the server and the client. The server reads the room
 * state when it resolves a roll, and a client reads its view to show the
 * bonus it will roll with. A player's view lacks what the DM keeps, such as
 * a token's room monster, so there a bonus can be unknown, and the card
 * offers "Roll d20" with a typed bonus instead.
 */

/**
 * Every d20 roll: saves (a concentration or save-ends save among them),
 * death saves, checks, initiative and attacks. A death save is a save tied
 * to no ability, so a rule about saving throws in general reaches it and a
 * rule naming an ability does not.
 */
export type D20Test =
  | { kind: "save"; ability: AbilityKey; cause?: "concentration" | "saveEnds"; spell?: true }
  | { kind: "deathSave" }
  | { kind: "check"; ability: AbilityKey; skill?: SkillKey }
  /** A Dexterity check in 2024. */
  | { kind: "initiative" }
  | { kind: "attack"; range?: "melee" | "ranged"; spell?: true };

export function isSave(test: D20Test): test is Extract<D20Test, { kind: "save" | "deathSave" }> {
  return test.kind === "save" || test.kind === "deathSave";
}

export function isCheck(test: D20Test): test is Extract<D20Test, { kind: "check" | "initiative" }> {
  return test.kind === "check" || test.kind === "initiative";
}

/** The ability a test rolls: Dexterity for initiative, none for a death save or an attack. */
export function abilityOf(test: D20Test): AbilityKey | undefined {
  if (test.kind === "save" || test.kind === "check") return test.ability;
  return test.kind === "initiative" ? "dex" : undefined;
}

export type RollNumbers = {
  /** `check` is an ability check's bonus where it is not the modifier. */
  abilities: Record<AbilityKey, { mod: number; save: number; check?: number }>;
  /** A skill's whole bonus with its usual ability. */
  skills: Partial<Record<SkillKey, number>>;
  /** The whole spell save DC and spell attack bonus. */
  spellDc?: number;
  spellAttack?: number;
  /** A death save's bonus, such as a Cloak of Protection's (docs/design-v1-pc-stats.md 5). */
  deathSave?: number;
};

/** Every SRD creature's numbers by its id, generated by docs/design-v1-roll-options.md's step 1 into shared/srd/rolls.json. */
export type SrdRolls = Record<SrdId, RollNumbers>;

/** What a creature's numbers are read from: the room state, or a viewer's projection of it, and the SRD table where it is loaded. */
export type RollSources = {
  tokens: Readonly<Record<string, Token>>;
  characters: Readonly<Record<string, Character>>;
  companionBlocks: Readonly<Record<string, CompanionBlock>>;
  monsters?: Readonly<Record<string, CustomMonster>>;
  srd?: SrdRolls | null;
};

/**
 * A test's bonus from a creature's numbers: a save its ability's save, a
 * death save `deathSave` or 0, and a check its ability's check or modifier.
 * A skill listed with its usual ability reads its whole bonus, and with
 * another ability carries over what the skill adds to the usual one, as the
 * SRD lets a check pair a skill with any ability. An unlisted skill reads as
 * a check of its ability. Initiative and attacks have no bonus here: the
 * actor holds initiative and an attack's NamedRoll its own.
 */
export function bonusFor(numbers: RollNumbers, test: D20Test): number | null {
  switch (test.kind) {
    case "save":
      return numbers.abilities[test.ability].save;
    case "deathSave":
      return numbers.deathSave ?? 0;
    case "check": {
      const ability = numbers.abilities[test.ability];
      const plain = ability.check ?? ability.mod;
      if (!test.skill) return plain;
      const skilled = numbers.skills[test.skill];
      if (skilled === undefined) return plain;
      const usual = SKILLS[test.skill].ability;
      return usual === test.ability ? skilled : ability.mod + skilled - numbers.abilities[usual].mod;
    }
    case "initiative":
    case "attack":
      return null;
  }
}

function inlineActor(sources: RollSources, token: Token): { actor: Actor; character?: Character } | null {
  if ("inline" in token.actor) return { actor: token.actor.inline };
  const character = sources.characters[token.actor.ref];
  return character ? { actor: character.actor, character } : null;
}

/**
 * A character's numbers (docs/design-v1-pc-stats.md 3.6): with an SRD
 * shape linked on its actor, Wild Shape without a stat block or another
 * shape such as Polymorph, the creature's own numbers. Doc 2 adds Wild Shape
 * with a stat block, which mixes the druid's and the beast's. With no shape,
 * its stat block's.
 */
function characterNumbers(sources: RollSources, character: Character): RollNumbers | null {
  const shape = character.actor.srdId;
  if (shape !== undefined) return sources.srd?.[shape] ?? null;
  return pcRollNumbers(character);
}

/**
 * The numbers a creature rolls with, by what it has: a character, or a
 * token of one, by the character's rule, and a token's own actor by the
 * stat block it links (a companion's block, a room monster or an SRD
 * creature). Null for anything else, or a source `sources` lacks.
 */
export function creatureNumbers(sources: RollSources, creature: ActorTarget): RollNumbers | null {
  if ("characterId" in creature) {
    const character = sources.characters[creature.characterId];
    return character ? characterNumbers(sources, character) : null;
  }
  const token = sources.tokens[creature.tokenId];
  if (!token) return null;
  if ("ref" in token.actor) {
    const character = sources.characters[token.actor.ref];
    return character ? characterNumbers(sources, character) : null;
  }
  const actor = token.actor.inline;
  if (actor.blockId !== undefined) {
    const block = sources.companionBlocks[actor.blockId];
    return block ? blockRollNumbers(block) : null;
  }
  if (actor.monsterId !== undefined) {
    const monster = sources.monsters?.[actor.monsterId];
    return monster ? blockRollNumbers(monster) : null;
  }
  if (actor.srdId !== undefined) return sources.srd?.[actor.srdId] ?? null;
  return null;
}

/**
 * A creature's bonus for a test, or null when none is known. Initiative is
 * the actor's own `initBonus` (doc 2 adds a shaped druid's), and an attack's
 * is its NamedRoll's, never the creature's.
 */
export function creatureBonus(sources: RollSources, creature: ActorTarget, test: D20Test): number | null {
  if (test.kind === "attack") return null;
  if (test.kind === "initiative") {
    if ("characterId" in creature) return sources.characters[creature.characterId]?.actor.initBonus ?? null;
    const token = sources.tokens[creature.tokenId];
    return token ? (inlineActor(sources, token)?.actor.initBonus ?? null) : null;
  }
  const numbers = creatureNumbers(sources, creature);
  return numbers ? bonusFor(numbers, test) : null;
}

/**
 * A request's choice as a D20Test (6.1), with the request's public context:
 * "against a spell" and a save-ends cause (docs/design-v1-roll-request.md
 * 1.1). No request asks a concentration save. A choice the test does not
 * offer reads as its first, as `roll.answer` does.
 */
export function testOf(request: Pick<RollRequest, "test"> & { spell?: true; cause?: "saveEnds" }, choice: number = 0): D20Test {
  const picked = request.test.choices[choice] ?? request.test.choices[0]!;
  if (request.test.kind === "save") {
    const save: Extract<D20Test, { kind: "save" }> = { kind: "save", ability: picked.ability };
    if (request.cause === "saveEnds") save.cause = "saveEnds";
    if (request.spell) save.spell = true;
    return save;
  }
  return picked.skill ? { kind: "check", ability: picked.ability, skill: picked.skill } : { kind: "check", ability: picked.ability };
}

const SKILL_BY_NAME = new Map<string, SkillKey>(Object.entries(SKILLS).map(([key, skill]) => [skill.name.toLowerCase(), key as SkillKey]));
const SIGNED = /^(.+?)\s*([+\-−–])\s*(\d+)$/;

function signedNumber(sign: string, digits: string): number {
  return (sign === "+" ? 1 : -1) * Number(digits);
}

/**
 * A room monster's or a companion's numbers from its stat block: each
 * ability's modifier from its score and its save as printed, the skills
 * line ("Perception +5, Stealth +4") read by name in any case with unknown
 * names left out, and the spell save DC and attack from the first entry
 * named "Spellcasting..." among its traits and actions.
 */
export function blockRollNumbers(block: Pick<StatBlock, "abilities" | "skills" | "traits" | "actions">): RollNumbers {
  const abilities = {} as RollNumbers["abilities"];
  for (const key of ABILITY_KEYS) abilities[key] = { mod: abilityMod(block.abilities[key].score), save: block.abilities[key].save };
  const skills: RollNumbers["skills"] = {};
  for (const part of block.skills.split(",")) {
    const m = SIGNED.exec(part.trim());
    const skill = m ? SKILL_BY_NAME.get(m[1]!.trim().toLowerCase()) : undefined;
    if (m && skill) skills[skill] = signedNumber(m[2]!, m[3]!);
  }
  const out: RollNumbers = { abilities, skills };
  const spellcasting = [...block.traits, ...block.actions].find((e) => /^spellcasting/i.test(e.name.trim()));
  if (spellcasting) {
    const dc = /spell save DC\s*(\d+)/i.exec(spellcasting.text);
    if (dc) out.spellDc = Number(dc[1]);
    const attack = /([+\-−–])\s*(\d+)\s+to hit with spell attacks/i.exec(spellcasting.text);
    if (attack) out.spellAttack = signedNumber(attack[1]!, attack[2]!);
  }
  return out;
}

/**
 * A character's numbers from its stat block (docs/design-v1-pc-stats.md 5):
 * every skill with its whole bonus, so Jack of All Trades needs no rule in
 * bonusFor, a check only where the checks bonus moves it off the modifier,
 * the spell numbers with a spellcasting ability, and a death save's bonus
 * from the bonus to every save. Null without a block, where the card offers
 * "Roll d20" with a typed bonus.
 */
export function pcRollNumbers(character: Pick<Character, "stats" | "level">): RollNumbers | null {
  if (!character.stats) return null;
  const d = pcDerived(character.stats, character.level);
  const abilities = {} as RollNumbers["abilities"];
  for (const key of ABILITY_KEYS) {
    abilities[key] = d.allChecks !== 0 ? { mod: d.mods[key], save: d.saves[key].total, check: d.checks[key].total } : { mod: d.mods[key], save: d.saves[key].total };
  }
  const skills: RollNumbers["skills"] = {};
  for (const key of SKILL_KEYS) skills[key] = d.skills[key].total;
  const out: RollNumbers = { abilities, skills };
  if (d.spell) {
    out.spellDc = d.spell.dc.total;
    out.spellAttack = d.spell.attack.total;
  }
  if (d.allSaves !== 0) out.deathSave = d.allSaves;
  return out;
}

/** One damage part of a named roll: canonical text "1d6+2", its type, and for an optional part its clause and own name. */
export type DamagePart = {
  formula: string;
  type?: DamageType;
  /** Its clause goes on "if", "when" or "while". */
  optional?: true;
  /** An optional part's own name, "Sneak Attack" (doc 2's riders). */
  name?: string;
  /** Dice added per slot above the spell's `level` (doc 2). */
  upcast?: string;
};

/**
 * One roll a creature can make by name (6.2): an attack, a save action, damage,
 * healing or a plain roll, one shape for monsters, companions and
 * characters, so one list renders them all. Made by doc 3's
 * blockActions(view), doc 2's pcNamedRolls(character) and pcSlots(character, key).
 */
export type NamedRoll = {
  /** Unique in its block: doc 3's section and name, or doc 2's roll id. */
  key: string;
  name: string;
  section: "traits" | "actions" | "bonusActions" | "reactions" | "legendaryActions" | "spells";
  /** The to-hit bonus, rolled as d20Formula(attack) with the mode beside it. */
  attack?: number;
  save?: { ability: AbilityKey; dc: number; onPass: "half" | "none" };
  damage: DamagePart[];
  /** Applied as healing. */
  heal?: { formula: string; upcast?: string };
  /** A plain roll, neither damage nor healing: Bardic Inspiration's 1d8 (doc 2). */
  dice?: string;
  /** The lowest face that recharges it. */
  recharge?: 2 | 3 | 4 | 5 | 6;
  /** "2/Day", as printed. */
  uses?: string;
  /** What a failed save gives, as the text names them. */
  conditions?: ConditionKey[];
  /** A weapon's wider critical range, sent as dice.roll's `critOn` (doc 2). */
  critOn?: 18 | 19;
  /** "Repeats the save at the end of each of its turns". */
  saveEnds?: true;
  /** "Until the end of its next turn" (target), "the dragon's next turn" (self). */
  lasts?: { at: "start" | "end"; of: "target" | "self" };
  /** A spell's level, 0 for a cantrip (doc 2). */
  level?: number;
};
