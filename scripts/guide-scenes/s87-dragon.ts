export default async (c: any) => {
  const dm = c.state.dm;
  const b = { w: 30, h: 20 };
  await dm.keyboard.press("Escape");
  await c.harness.pickTool(dm, "Select");
  await c.harness.openSideTab(dm, "Scenes");
  await dm.getByText("Dragon's lair", { exact: true }).first().click();
  await dm.waitForTimeout(2000);
  await c.harness.openSideTab(dm, "Monsters");
  const panel = dm.locator('[role="tabpanel"]').first();
  const back = panel.getByRole("button", { name: "Back to Monsters" });
  if (await back.count()) await back.click();
  await dm.getByLabel("Search monsters").fill("red dragon");
  await dm.waitForTimeout(600);
  await panel.getByText("Adult Red Dragon", { exact: true }).first().click();
  await dm.waitForTimeout(600);
  const card = await panel.innerText();
  await panel.getByLabel("In its lair").check();
  await dm.waitForTimeout(300);
  await panel.getByRole("button", { name: /^Place on the map/ }).click();
  await dm.waitForTimeout(400);
  await c.harness.tapCell(dm, b, { x: 20, y: 11 });
  await dm.waitForTimeout(1000);
  await dm.keyboard.press("Escape");
  const { pcToken } = await import(`./lib.ts?t=${Date.now()}`);
  const ids: Record<string, string> = {};
  const spots: Record<string, [number, number]> = { thorn: [10, 10], bree: [9, 12], mara: [11, 13], ivo: [7, 11] };
  for (const [k, [x, y]] of Object.entries(spots)) ids[k] = await pcToken(c, c.state.lair, k, x, y, { image: c.state.icons[k] });
  c.state.lairPcs = ids;
  return card.slice(0, 700);
};
