import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { existsSync, lstatSync, readFileSync } from "node:fs";
import path from "node:path";
import { describe, test } from "node:test";
import { fileURLToPath } from "node:url";

/*
 * Every file in the repository keeps .editorconfig's layout, checked here so
 * CI enforces it (docs/development.md, coding standards): UTF-8 with no byte
 * order mark, LF line endings, a final newline, indents of spaces and no
 * trailing spaces or tabs, which Markdown may keep, since two of them end a
 * line with a break there. The width of an indent is left to the editor:
 * comment blocks and Markdown lists indent by odd counts on purpose.
 */

const ROOT = fileURLToPath(new URL("..", import.meta.url));

type Rule = "utf-8" | "lf" | "final newline" | "space indent" | "no trailing whitespace";

/** File types that hold no text. Any other file is read as text, so a new binary type needs adding here. */
const BINARY = /\.(mp4|pdf|png|webm|webp|woff2)$/;

/** Files that keep one rule broken, each for the reason given. */
const EXEMPT = new Map<string, Rule>([
  // Written by scripts/game-icons.ts as one JSON.stringify line, and served as immutable from a folder named for the pinned commit, so it stays byte for byte what the script makes.
  ["public/game-icons/82d94881/index.json", "final newline"],
  // The room and ops as the build before op version 20 wrote them, kept byte for byte as the record shared/reducer/opVersion19.test.ts replays.
  ["shared/reducer/opVersion19.fixture.json", "final newline"],
  // Generated by scripts/selfhost-compose.ts, which embeds the https profile's Caddyfile indented with tabs, the way Caddy's own formatter writes one.
  ["selfhost/compose.yml", "space indent"],
]);

/** The rules one file breaks, each with its first line, or 0 for a rule of the whole file. */
function layoutProblems(file: string, bytes: Uint8Array): { rule: Rule; line: number }[] {
  if (bytes[0] === 0xef && bytes[1] === 0xbb && bytes[2] === 0xbf) return [{ rule: "utf-8", line: 0 }];
  let text: string;
  try {
    text = new TextDecoder("utf-8", { fatal: true }).decode(bytes);
  } catch {
    return [{ rule: "utf-8", line: 0 }];
  }
  // A NUL is valid UTF-8 but no text file holds one, so this is a binary type BINARY lacks.
  if (text.includes("\0")) return [{ rule: "utf-8", line: 0 }];
  const problems: { rule: Rule; line: number }[] = [];
  const lines = text.split("\n");
  const first = (rule: Rule, broken: (line: string) => boolean) => {
    const at = lines.findIndex(broken);
    if (at >= 0) problems.push({ rule, line: at + 1 });
  };
  first("lf", (l) => l.includes("\r"));
  if (text !== "" && !text.endsWith("\n")) problems.push({ rule: "final newline", line: lines.length });
  first("space indent", (l) => /^[ ]*\t/.test(l));
  if (!file.endsWith(".md")) first("no trailing whitespace", (l) => /[ \t]\r?$/.test(l));
  return problems;
}

/** Every file git tracks or would add, as it is in the working tree. */
function repositoryFiles(): string[] {
  const listed = execFileSync("git", ["ls-files", "-z", "--cached", "--others", "--exclude-standard"], { cwd: ROOT, encoding: "utf8", maxBuffer: 64 * 1024 * 1024 });
  return [...new Set(listed.split("\0").filter(Boolean))].filter((f) => existsSync(path.join(ROOT, f)) && lstatSync(path.join(ROOT, f)).isFile()).sort();
}

const encode = (text: string) => new TextEncoder().encode(text);
const rules = (file: string, text: string) => layoutProblems(file, encode(text)).map((p) => `${p.rule} ${p.line}`);

describe(".editorconfig's layout", () => {
  test("is the layout this check enforces", () => {
    const sections: Record<string, Record<string, string>> = {};
    let section = "";
    for (const line of readFileSync(path.join(ROOT, ".editorconfig"), "utf8").split("\n")) {
      const header = /^\[(.+)\]$/.exec(line);
      const pair = /^(\w+)\s*=\s*(\S+)$/.exec(line);
      if (header) sections[(section = header[1]!)] = {};
      else if (pair && section) sections[section]![pair[1]!] = pair[2]!;
    }
    assert.deepEqual(
      sections,
      {
        "*": { charset: "utf-8", end_of_line: "lf", indent_style: "space", indent_size: "2", insert_final_newline: "true", trim_trailing_whitespace: "true" },
        "*.md": { trim_trailing_whitespace: "false" },
      },
      "a change to .editorconfig changes what layoutProblems checks",
    );
  });

  test("every file in the repository keeps it", (t) => {
    // A source archive has no git to list its files. CI always checks out with git.
    if (!existsSync(path.join(ROOT, ".git")) && !process.env.CI) return t.skip("not a git checkout");
    const files = repositoryFiles();
    assert.ok(files.length > 1000, "git listed the repository's files");
    const found: string[] = [];
    for (const file of files) {
      if (BINARY.test(file)) continue;
      for (const { rule, line } of layoutProblems(file, readFileSync(path.join(ROOT, file)))) {
        if (EXEMPT.get(file) !== rule) found.push(`${file}${line ? `:${line}` : ""}: ${rule}`);
      }
    }
    assert.deepEqual(found, [], "fix the layout, or for a binary file type add it to BINARY");
  });

  test("each exemption is still needed", () => {
    for (const [file, rule] of EXEMPT) {
      const problems = layoutProblems(file, readFileSync(path.join(ROOT, file))).map((p) => p.rule);
      assert.deepEqual(problems, [rule], `${file} breaks only the rule it is exempt from`);
    }
  });

  test("finds each rule broken, on the first line that breaks it", () => {
    assert.deepEqual(rules("a.ts", "one\n  two\n"), []);
    assert.deepEqual(rules("a.ts", ""), []);
    assert.deepEqual(rules("a.ts", "one\r\ntwo \r\n"), ["lf 1", "no trailing whitespace 2"]);
    assert.deepEqual(rules("a.ts", "one\ntwo"), ["final newline 2"]);
    assert.deepEqual(rules("a.ts", "one\n\ttwo\n"), ["space indent 2"]);
    assert.deepEqual(rules("a.ts", "one\n  \ttwo\n"), ["space indent 2"]);
    assert.deepEqual(rules("a.ts", "a\tb\n"), [], "a tab after the indent is text");
    assert.deepEqual(rules("a.ts", "one\ntwo \n"), ["no trailing whitespace 2"]);
    assert.deepEqual(rules("a.ts", "one\t\n"), ["no trailing whitespace 1"]);
    assert.deepEqual(rules("a.md", "a line break  \nthen more\n"), []);
    assert.deepEqual(rules("a.md", "one\n\ttwo\n"), ["space indent 2"], "Markdown keeps every rule but trailing spaces");
  });

  test("reads only UTF-8 text, with no byte order mark", () => {
    assert.deepEqual(rules("a.ts", "\u{FEFF}one\n"), ["utf-8 0"]);
    assert.deepEqual(layoutProblems("a.ts", new Uint8Array([0x6f, 0xe9, 0x0a])), [{ rule: "utf-8", line: 0 }], "Latin-1 é");
    assert.deepEqual(layoutProblems("a.ts", new Uint8Array([0x89, 0x50, 0x4e, 0x47, 0x00, 0x0a])), [{ rule: "utf-8", line: 0 }], "an unlisted binary file");
    assert.deepEqual(rules("a.ts", "café, naïve ✓\n"), []);
  });
});
